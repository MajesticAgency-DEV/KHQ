function loadLayout() {
    // Load header
    fetch("layout/header.html")
        .then(res => res.text())
        .then(html => {
            var headerEl = document.getElementById("header");
            if (headerEl) {
                headerEl.innerHTML = html;
                // Signal that header markup is now in the DOM so scripts can re-init behaviors
                document.dispatchEvent(new CustomEvent("header:loaded"));
            }
        })
        .catch(function(){ /* ignore header load errors */ });

    // Load footer
    var footerEl = document.getElementById("footer");
    if (footerEl) {
        fetch("layout/footer.html")
            .then(res => res.text())
            .then(html => {
                footerEl.innerHTML = html;
                // Signal that footer markup is now in the DOM so scripts can adjust sizing
                document.dispatchEvent(new CustomEvent("footer:loaded"));
            })
            .catch(function(){ /* ignore footer load errors */ });
    }
}

document.addEventListener("DOMContentLoaded", loadLayout);

// Generated by Cursor: ensure footer-dependent API is invoked once when footer is loaded
(function(){
	var footerDataLoaded = false;
	function loadFooterOnce() {
		if (footerDataLoaded) return;
		// Ensure footer placeholders exist before proceeding. If not, wait for footer:loaded.
		var addressEl = document.getElementById("footer-address");
		var emailEl = document.getElementById("footer-email");
		var phoneEl = document.getElementById("footer-phone");
		var catList = document.getElementById("footer-categories");
		if (!addressEl || !emailEl || !phoneEl) return;

		// From here on, we are safe to mark as loaded to avoid duplicate fetch
		footerDataLoaded = true;

		// Prefer fetch over $.ajax so this works even if jQuery isn't present yet
		fetch("/api/SocialMedia/GetAll", { method: "GET" })
			.then(function(res){ return res.ok ? res.json() : Promise.reject(res); })
			.then(function (data) {

				fetch("/api/ContactUs/GetAll", { method: "GET" })
					.then(function (res) { return res.ok ? res.json() : Promise.reject(res); })
					.then(function (data) {
						var itemContactUs = Array.isArray(data) && data.length ? data[0] : data || {};

						// Address
						if (itemContactUs.companyLocation) {
							addressEl.textContent = itemContactUs.companyLocation;
						}

						// Email
						if (itemContactUs.email) {
							emailEl.textContent = itemContactUs.email;
							//emailEl.href = "mailto:" + itemContactUs.email;
						}

						// Phone
						if (itemContactUs.phoneNumber) {
							var tel = itemContactUs.phoneNumber.replace(/\s+/g, "");
							phoneEl.textContent = itemContactUs.phoneNumber;
							//phoneEl.href = "tel:" + tel;
						}
					})
					.catch(function (err) {
						if (window && window.console) {
							console.warn("SocialMedia GetAll request failed", err && err.status ? err.status : err);
						}
					});

				// Footer categories
				if (catList) {
					fetch("/api/Category/GetAll", { method: "GET" })
						.then(function (res) { return res.ok ? res.json() : Promise.reject(res); })
						.then(function (payload) {
							try {
								var items = payload.CategoriesDtos || payload.categoriesDtos || [];
								if (!Array.isArray(items)) items = [];
								var html = items.map(function (c) {
									var id = c.Id || c.id;
									var name = c.Name || c.name || '';
									var href = id ? ('products.html?categoryId=' + encodeURIComponent(id)) : 'javascript:void(0);';
									return '<li><a href="' + href + '">' + name + '</a></li>';
								}).join('');
								catList.innerHTML = html;
							} catch (_e) { }
						})
						.catch(function (err) {
							if (window && window.console) {
								console.warn('Footer Category GetAll failed', err && err.status ? err.status : err);
							}
						});
				}

				var item = Array.isArray(data) && data.length ? data[0] : data || {};

				// Social links
				var fb = document.getElementById("sm-facebook");
				var ig = document.getElementById("sm-instagram");
				var wa = document.getElementById("sm-whatsapp");
				var web = document.getElementById("sm-website");

				if (fb && item.faceLink) fb.href = item.faceLink; else if (fb) fb.style.display = "none";
				if (ig && item.instaLink) ig.href = item.instaLink; else if (ig) ig.style.display = "none";
				if (wa && item.whatsAppLink) wa.href = item.whatsAppLink; else if (wa) wa.style.display = "none";
				if (web && item.webSiteLink) web.href = item.webSiteLink; else if (web) web.style.display = "none";
			})
			.catch(function(err){
				if (window && window.console) {
					console.warn("SocialMedia GetAll request failed", err && err.status ? err.status : err);
				}
			});
	}

	// Call once when the footer fragment is injected
	document.addEventListener("footer:loaded", loadFooterOnce);
	// Also guard-call on DOM ready/full load in case event ordering differs
	document.addEventListener("DOMContentLoaded", loadFooterOnce);
	window.addEventListener("load", loadFooterOnce);
})();

(function(){
    function getCookie(name){
        var nameEQ = name + "=";
        var ca = document.cookie.split(';');
        for (var i=0;i<ca.length;i++){
            var c = ca[i];
            while (c.charAt(0)==' ') c = c.substring(1,c.length);
            if (c.indexOf(nameEQ)==0) return c.substring(nameEQ.length,c.length);
        }
        return null;
    }

    function currentCulture(){
        var v = getCookie('.AspNetCore.Culture');
        if(!v){ return 'en'; }
        var m = /c=([^\|]+)/.exec(v);
        return m && m[1] ? m[1] : 'en';
    }

    var translationsCache = null;
    function loadTranslations(){
        if (translationsCache) return Promise.resolve(translationsCache);
        return fetch('/i18n/translations.json', { credentials: 'same-origin' })
            .then(function(r){ return r.json(); })
            .then(function(json){ translationsCache = json || {}; return translationsCache; })
            .catch(function(){ translationsCache = {}; return translationsCache; });
    }

    function updateTexts(){
        var cur = currentCulture();
        var curEl = document.getElementById('lang-current');
        if (curEl){ curEl.textContent = cur.toUpperCase(); }
        //if (cur === 'ar'){
        //    document.documentElement.setAttribute('dir','rtl');
        //    document.documentElement.setAttribute('lang','ar');
        //} else {
        //    document.documentElement.setAttribute('dir','ltr');
        //    document.documentElement.setAttribute('lang','en');
        //}

        loadTranslations().then(function(map){
            var dict = (map && map[cur]) ? map[cur] : {};
            var nodes = document.querySelectorAll('[data-i18n-key]');
            for (var i=0;i<nodes.length;i++){
                var key = nodes[i].getAttribute('data-i18n-key');
                if (key && dict[key]){
                    nodes[i].textContent = dict[key];
                }
            }
        });
    }

    function attachHandlers(){
        var options = document.querySelectorAll('.lang-option');
        for (var i=0;i<options.length;i++){
            options[i].addEventListener('click', function(e){
                e.preventDefault();
                var lang = this.getAttribute('data-lang') || 'en';
                // Persist culture in cookie and update UI
                var cookieVal = 'c=' + encodeURIComponent(lang) + '|uic=' + encodeURIComponent(lang);
                var expires = new Date(Date.now() + 365*24*60*60*1000).toUTCString();
                document.cookie = '.AspNetCore.Culture=' + cookieVal + '; expires=' + expires + '; path=/';
                updateTexts();
                location.reload();
            });
        }
    }

    function initHeaderI18n(){
        attachHandlers();
        updateTexts();
    }

    document.addEventListener('header:loaded', initHeaderI18n);
})();

(function () {
    // Handle clicking a top-level has-child link
    document.addEventListener("click", function (e) {
        const target = e.target.closest(".header-nav .nav > li.has-child > a");
        if (target) {
            const li = target.closest("li.has-child");
            if (li) {
                // Remove active/nav-active from siblings
                const siblings = li.parentElement.querySelectorAll(".has-child");
                siblings.forEach(sib => {
                    if (sib !== li) {
                        sib.classList.remove("active", "nav-active");
                    }
                });
                li.classList.add("active");
            }
        }
    });

    // Handle submenu toggle icon
    document.addEventListener("click", function (e) {
        const toggleBtn = e.target.closest(".header-nav .nav > li.has-child > .submenu-toogle");
        if (toggleBtn) {
            const li = toggleBtn.closest("li.has-child");
            if (li) {
                const siblings = li.parentElement.querySelectorAll(".has-child");
                siblings.forEach(sib => {
                    if (sib !== li) {
                        sib.classList.remove("active", "nav-active");
                    }
                });
                li.classList.add("active");
            }
        }
    });
})();

(function () {
    function normalizeToFile(href) {
        if (!href) return "index.html";
        href = href.toLowerCase();

        // Map "/", "./", "index", "index/" → index.html
        if (href === "/" || href === "./" || href === "index" || href === "index/") {
            return "index.html";
        }

        // Otherwise, get last part after slash
        const file = href.substring(href.lastIndexOf("/") + 1);
        return file || "index.html";
    }

    function setActiveMenuFromUrl() {
        const path = (window.location.pathname || "").toLowerCase();
        let currentFile;

        if (path === "/" || path === "" || path.endsWith("/")) {
            currentFile = "index.html";
        } else {
            currentFile = path.substring(path.lastIndexOf("/") + 1);
        }

        const items = document.querySelectorAll(".header-nav .nav > li.has-child");
        if (!items.length) return;

        items.forEach(item => item.classList.remove("active", "nav-active"));

        const match = Array.from(items).find(item => {
            const link = item.querySelector("a");
            const linkHref = link ? link.getAttribute("href") || "" : "";
            const hrefFile = normalizeToFile(linkHref);
            return hrefFile === currentFile;
        });

        if (match) {
            match.classList.add("active");
        }
    }

    // When header fragment is injected
    document.addEventListener("header:loaded", setActiveMenuFromUrl);
    // Also run on full window load
    window.addEventListener("load", setActiveMenuFromUrl);
})();